const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const {createRequire} = require('node:module')
const assert = require('node:assert/strict')
const localRequire = createRequire(path.resolve('frontend/package.json'))
const ts = localRequire('typescript')
const React = localRequire('react')
const {renderToStaticMarkup} = localRequire('react-dom/server')
const source = fs.readFileSync('frontend/src/AssistantMessageBody.tsx','utf8')
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText
const moduleForTest = {exports:{}}
vm.runInNewContext(compiled,{module:moduleForTest,exports:moduleForTest.exports,require:localRequire})
const Body = moduleForTest.exports.default
const render = content => renderToStaticMarkup(React.createElement(Body,{content}))
const sections=['检测结果解读','叶片可见异常','虫害线索','现在可以做什么','复拍与复检建议','何时联系农技人员']
const full = render(sections.map((title,index)=>`${index+1}. ${title}\n请结合田间情况确认。`).join('\n\n'))
assert.equal((full.match(/<h4>/g)||[]).length,6)
assert.equal((full.match(/<p>/g)||[]).length,6)
const formatted = render('## 观察结论\n保留 **原始照片** 和 `日期`。\n\n- 叶片正面\n- 叶片背面\n\n1. 标记植株\n2. 安排复检')
assert.ok(formatted.includes('<strong>原始照片</strong>'))
assert.ok(formatted.includes('<code>日期</code>'))
assert.equal((formatted.match(/<li>/g)||[]).length,4)
assert.ok(formatted.includes('<ul>')&&formatted.includes('<ol'))
const unsafe = render('<script>alert("test")</script>\n<img src=x onerror=alert(1)>\n**<button>fake</button>**')
assert.ok(unsafe.includes('&lt;script&gt;')&&unsafe.includes('&lt;img'))
assert.ok(!unsafe.includes('<script')&&!unsafe.includes('<img')&&!unsafe.includes('<button'))
assert.ok(render('1. **检测结果解读**：请复检。').includes('<h4>'))
const chinese = render('一、检测结果解读\n观察叶片。\n\n二、复检建议\n安排复拍。')
assert.ok(chinese.includes('>一</span>')&&chinese.includes('>二</span>'))
assert.ok(!chinese.includes('0一')&&!chinese.includes('0二'))
assert.ok(render('1. 检测结果解读\n观察叶片。').includes('>01</span>'))
const report = {status:'passed',checks:['Six supplied plain-text analysis sections remain in order','Paragraphs bold inline code and unordered/ordered lists render as readable blocks','Model-supplied HTML remains escaped React text, never executable markup','Inline bold section heading with explanation is recognized','Chinese section numbers retain their original labels while numeric labels use two digits'],source:'Actual AssistantMessageBody.tsx transpiled and rendered with installed React; no network'}
fs.writeFileSync('.runtime/assistant-ui-20261029/render-check.json',JSON.stringify(report,null,2))
console.log(JSON.stringify(report))
