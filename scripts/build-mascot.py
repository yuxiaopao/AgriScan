"""Package generated Xiaohe frames using the desktop-pet skill's extraction/QA.

Artwork is generated by image_gen. This script only extracts, registers and
encodes those pixels; it never draws or synthesizes character poses.
"""
import argparse
import importlib.util
import json
from pathlib import Path

from PIL import Image, ImageDraw


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--skill-dir", required=True, type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    work = root / "design/xiaohe-motion"
    public = root / "frontend/public/images/xiaohe-motion"
    public.mkdir(parents=True, exist_ok=True)
    extract = module("pet_extract", args.skill_dir / "scripts/extract_strip_frames.py")
    inspect = module("pet_inspect", args.skill_dir / "scripts/inspect_frames.py")
    states = ["idle", "wave", "scan", "think", "success", "concern"]
    qa_args = argparse.Namespace(require_components=True, allow_stable_slots=False,
                                 edge_margin=2, min_used_pixels=400, edge_pixel_threshold=24,
                                 chroma_adjacent_threshold=150, chroma_adjacent_pixel_threshold=800,
                                 small_outlier_ratio=0.8, large_outlier_ratio=1.25)
    reports = []
    contact = Image.new("RGB", (8 * 192, 6 * 234), "#f2f5ed")
    draw = ImageDraw.Draw(contact)
    previews = []
    for row, state in enumerate(states):
        image = Image.open(work / "source" / f"{state}.png").convert("RGBA")
        groups = extract.component_frame_groups(image, 8)
        if not groups or len(groups) != 8:
            raise ValueError(f"{state}: expected eight separated full-body poses")
        bounds = [extract.component_bounds(group) for group in groups]
        # The generated final wave touches the source boundary. Close the loop
        # with its intact opening pose instead of retaining a clipped hand/leaf.
        repaired = []
        for index, box in enumerate(bounds):
            if box[0] == 0 or box[2] == image.width:
                if state == "wave" and index == 7:
                    groups[index] = groups[0]
                    repaired.append({"frame": index, "source_frame": 0, "reason": "clipped source edge; loop closure"})
                else:
                    raise ValueError(f"{state}: clipped source frame {index}")
        frames = extract.fit_registered_component_groups(image, groups)
        folder = work / "frames" / state
        folder.mkdir(parents=True, exist_ok=True)
        strip = Image.new("RGBA", (192 * 8, 208))
        for index, frame in enumerate(frames):
            frame.save(folder / f"{index:02d}.png")
            strip.alpha_composite(frame, (index * 192, 0))
            contact.paste(frame, (index * 192, row * 234 + 24), frame)
        strip.save(public / f"{state}.webp", lossless=True, method=6)
        draw.text((12, row * 234 + 5), state.upper(), fill="#315239")
        preview = []
        for frame in frames:
            canvas = Image.new("RGB", frame.size, "#f2f5ed")
            canvas.paste(frame, mask=frame.getchannel("A"))
            preview.append(canvas)
        preview[0].save(work / f"{state}.gif", save_all=True, append_images=preview[1:],
                        duration=150 if state != "idle" else 220, loop=0, disposal=2)
        previews.extend(preview * 2)
        report = inspect.inspect_state(work / "frames", state, 8,
                                       {state: {"method": "components"}}, None, qa_args)
        report["source_adjustments"] = repaired
        report["encoded_bytes"] = (public / f"{state}.webp").stat().st_size
        reports.append(report)
        if not report["ok"] or report["warnings"]:
            raise ValueError(json.dumps(report, ensure_ascii=False))
    contact.save(work / "contact-sheet.jpg", quality=92)
    previews[0].save(work / "motion-preview.gif", save_all=True, append_images=previews[1:],
                     duration=150, loop=0, disposal=2)
    result = {"ok": all(row["ok"] for row in reports), "cell": [192, 208], "frames_per_state": 8,
              "states": reports, "total_encoded_bytes": sum(row["encoded_bytes"] for row in reports)}
    (work / "frame-review.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"ok": result["ok"], "states": states, "total_encoded_bytes": result["total_encoded_bytes"]}))


if __name__ == "__main__":
    main()
